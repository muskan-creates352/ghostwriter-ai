"use client";

import React, { useState } from "react";
import { GeneratedStory } from "../types";

interface StoryResultProps {
  story: GeneratedStory | null;
  isLoading: boolean;
  onRegenerate: () => void;
}

export const StoryResult: React.FC<StoryResultProps> = ({
  story,
  isLoading,
  onRegenerate,
}) => {
  const [copied, setCopied] = useState(false);

  const handleCopy = async () => {
    if (!story) return;
    try {
      const fullText =
        `# ${story.title}\n\n${story.content}\n\n---\nTopic: ${story.topic} | Genre: ${story.genre}\nEngine: ${story.engineInfo.name} (${story.engineInfo.version})`;
      await navigator.clipboard.writeText(fullText);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error("Clipboard copy failed", err);
    }
  };

  const handleDownload = () => {
    if (!story) return;
    const markdownContent =
      `# ${story.title}\n\n*Topic:* ${story.topic}\n*Genre:* ${story.genre}\n*Generated at:* ${story.createdAt}\n*Engine:* ${story.engineInfo.name} [DEMO / MOCK]\n\n---\n\n${story.content}\n\n---\n*Created with GhostWriter AI (Hacktoberfest 2026: Ghost in the Machine)*\n`;
    const blob = new Blob([markdownContent], {
      type: "text/markdown;charset=utf-8",
    });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${
      story.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")
    }.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  if (isLoading) {
    return (
      <div className="ghost-card p-8 text-center flex flex-col items-center justify-center min-h-[420px]">
        <div className="w-16 h-16 rounded-full border-2 border-emerald-500/20 border-t-emerald-400 animate-spin mb-4 shadow-[0_0_20px_rgba(16,185,129,0.3)]" />
        <h3 className="text-lg font-mono font-semibold text-emerald-400 ghost-glow-text mb-2">
          Interfacing with Digital Phantoms...
        </h3>
        <p className="text-xs text-slate-400 max-w-sm">
          Traversing unallocated sectors, checking stack frames, and extracting
          memory fragments for your story.
        </p>
      </div>
    );
  }

  if (!story) {
    return (
      <div className="ghost-card p-8 text-center flex flex-col items-center justify-center min-h-[420px] border-dashed border-slate-800">
        <div className="text-4xl mb-3 opacity-60">🔮</div>
        <h3 className="text-base font-semibold text-slate-300 mb-1">
          The Machine is Dormant
        </h3>
        <p className="text-xs text-slate-500 max-w-md">
          Choose a spooky topic on the left and click &ldquo;Generate Spooky
          Story&rdquo; to summon a tale from the digital abyss.
        </p>
        <div className="mt-4 px-3 py-1.5 rounded bg-slate-900/80 border border-slate-800 text-[11px] font-mono text-emerald-400/80">
          Ready for testing · No API keys required
        </div>
      </div>
    );
  }

  return (
    <div className="ghost-card p-6 shadow-2xl relative flex flex-col justify-between">
      {/* CLEARLY LABELED MOCK/DEMO BADGE AS REQUIRED */}
      <div className="mb-4 p-3 rounded-lg bg-amber-950/40 border border-amber-500/40 text-amber-200 flex items-start gap-2.5">
        <span className="text-lg leading-none">⚠️</span>
        <div className="flex-1">
          <div className="flex items-center gap-2">
            <span className="text-xs font-mono font-bold tracking-wider uppercase text-amber-300 bg-amber-500/20 px-1.5 py-0.5 rounded">
              Demo / Mock Mode
            </span>
            <span className="text-[11px] text-amber-400 font-medium">
              Procedural Story Engine
            </span>
          </div>
          <p className="text-xs text-amber-200/90 mt-1 leading-relaxed">
            This is an offline demo response generated by the local story
            template engine. No paid API or external AI model was called. An
            open-weight AI model (such as Llama 3 or Mistral) will be integrated
            in Phase 2.
          </p>
        </div>
      </div>

      {/* Story Metadata Header */}
      <div className="border-b border-slate-800 pb-4 mb-4">
        <div className="flex flex-wrap items-center justify-between gap-2 mb-2">
          <span className="text-xs font-mono uppercase px-2 py-0.5 rounded bg-emerald-950 text-emerald-300 border border-emerald-500/30">
            {story.genre.replace("-", " ")}
          </span>
          <div className="flex items-center gap-3 text-xs text-slate-400 font-mono">
            <span>⏱️ {story.readingTimeMinutes} min read</span>
            <span>📝 {story.wordCount} words</span>
            <span>🕒 {story.createdAt}</span>
          </div>
        </div>

        <h2 className="text-xl md:text-2xl font-bold text-white tracking-tight ghost-glow-text mt-1">
          {story.title}
        </h2>
        <div className="text-xs text-slate-400 font-mono mt-1">
          Prompt Seed: &ldquo;<span className="text-emerald-400">
            {story.topic}
          </span>&rdquo;
        </div>
      </div>

      {/* Story Content Area */}
      <div className="prose prose-invert max-w-none text-slate-200 leading-relaxed text-sm md:text-base space-y-4 my-2 font-serif selection:bg-emerald-900 selection:text-white">
        {story.content.split("\n\n").map((para, index) => (
          <p
            key={index}
            className="text-slate-200 text-sm md:text-base leading-relaxed"
          >
            {para}
          </p>
        ))}
      </div>

      {/* Action Buttons & Footer */}
      <div className="border-t border-slate-800 pt-4 mt-6">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div className="text-[11px] text-slate-500 font-mono">
            Target Model:{" "}
            <span className="text-slate-400">
              {story.engineInfo.modelTarget}
            </span>
          </div>

          <div className="flex items-center gap-2">
            {/* Copy Button */}
            <button
              type="button"
              onClick={handleCopy}
              className={`px-3.5 py-1.5 rounded-lg text-xs font-mono font-medium border transition-all flex items-center gap-1.5 ${
                copied
                  ? "bg-emerald-500/20 border-emerald-400 text-emerald-300"
                  : "bg-slate-900 border-slate-700 text-slate-300 hover:border-slate-500 hover:text-white"
              }`}
            >
              <span>{copied ? "✓ Copied!" : "📋 Copy Story"}</span>
            </button>

            {/* Download Button */}
            <button
              type="button"
              onClick={handleDownload}
              title="Download story as Markdown (.md)"
              className="px-3.5 py-1.5 rounded-lg text-xs font-mono font-medium bg-slate-900 border border-slate-700 text-slate-300 hover:border-slate-500 hover:text-white transition-all flex items-center gap-1.5"
            >
              <span>💾 Download (.md)</span>
            </button>

            {/* Regenerate Button */}
            <button
              type="button"
              onClick={onRegenerate}
              className="px-3.5 py-1.5 rounded-lg text-xs font-mono font-medium bg-emerald-950/60 border border-emerald-500/40 text-emerald-300 hover:bg-emerald-900/60 hover:border-emerald-400 transition-all flex items-center gap-1.5 shadow-[0_0_10px_rgba(16,185,129,0.2)]"
            >
              <span>🔄 Regenerate</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
